// =============================================================================
// Includes
// =============================================================================
#include "dls2/reflex/reflex.hpp"

// =============================================================================
// Using Declarations
// =============================================================================
using namespace dls;

// =============================================================================
// Constructors
// =============================================================================
Reflex::Reflex(size_t njoints_, bool(*predicate_)()) :
	njoints(njoints_),
	predicate(predicate_),
	zeroes()
{
	zeroes.resize(njoints);
	zeros = Eigen::VectorXd::zero(njoints);
}

// =============================================================================
// Implementation
// =============================================================================
Eigen::VectorXd run()
{
	if(this->predicate())
	{
		return this->calculateTorques();
	}
	else
	{
		return this->zeroes;
	}
}
