// =============================================================================
// Class Interface
// =============================================================================
// TODO a lot of functions have been removed from Controller. Many of them need to be put into Dog
namespace dls
{
class Controller : public PeriodicAppLayerComponent
{
	friend class ControlLayer;
	friend class GaitListener;
	friend class BlindStateListener;
public:
	// using ID_t = std::string;

	// Plugin typedefs
	typedef Controller *create_t(std::shared_ptr<dls::dog::Dog>);
	typedef void destroy_t(Controller*);

	Controller
	(
		const std::shared_ptr<dog::Dog>&,                   ///< A pointer to the robot model
		const ID_t&,                                        ///< The ID of the controller
		const period_t&,                                    ///< The period of the controller
		const ControlSignal::SignalReconstructionMethod&    ///< Signal reconstruction used by this controller
	);

	virtual ~Controller() = default;

	// This will be replaced by the shutdown and eStop functions
	// TODO unknown what this should do
	// virtual void kill() = 0;

	///// Get the ID of this controller
	/////
	///// @ret the ID
	//ID_t getID() const;

	/// Returns the name of the topic where this controller is publishing its
	/// control signal
	std::string getControlSignalTopic() const;

protected:
	///// Function gets called each epoch.
	/////
	///// @param time The time when this function is called,
	//virtual void run(const std::chrono::system_clock::time_point &time) = 0;

	/// Gets the current value of the signal generated by the active gait
	/// generator
	std::shared_ptr<const GaitSignal> readGaitSignal() const;

	std::shared_ptr<BlindState> readBlindStateSignal() const;

	/// Sends the control command to the rest of the architecture
	void publishSignal(const ControlSignal&);

	const std::shared_ptr<const dog::Dog> pDog;
	const std::string name;
	const ControlSignal::SignalReconstructionMethod signal_reconstruction_method;
	// const ID_t ID;

private:
	// BEGIN critical section
		/// The last reading of the signal from the current active gait generator
		std::shared_ptr<const GaitSignal> pGait_signal;
		mutable std::mutex gait_signal_mutex;
	// END critical section


	// BEGIN critical section
		std::shared_ptr<const ControlSignal> pControl_signal;
		mutable std::mutex control_signal_mutex;
	// END critical section

	// BEGIN critical section
		std::shared_ptr<BlindState> pBlind_state_signal;
		mutable std::mutex blind_state_signal_mutex;
	// END crital section

	std::atomic_bool should_run;

	// =============================== FastRTPS ================================
	class GaitListener : public SubscriberBase<GaitSignalMsgPubSubType>
	{
	public:
		GaitListener(std::shared_ptr<Controller>);
		~GaitListener() = default;
		void onNewDataMessage(eprosima::fastrtps::Subscriber*) override;
	private:
		const std::shared_ptr<Controller> pOwner;
		eprosima::fastrtps::SampleInfo_t info;
	} gait_listener;

	class BlindStateListener : public SubscriberBase<BlindStateMsgPubSubType>
	{
	public:
		BlindStateListener(std::shared_ptr<Controller>);
		~BlindStateListener() = default;
		void onNewDataMessage(eprosima::fastrtps::Subscriber*) override;
	private:
		const std::shared_ptr<Controller> pOwner;
		eprosima::fastrtps::SampleInfo_t info;
	} blind_state_listener;


	const std::string control_signal_topic;
	PublisherBase<ControlSignalMsgPubSubType> publisher;
};
} // end namespace dls

/// Export the controller for loading into the framework
///
#define DLS_EXPORT_CONTROLLER(controller) \
extern "C" dls::Controller *create(std::shared_ptr<dls::dog::Dog> pDog) \
{ \
	return new controller(pDog); \
} \
extern "C" void destroy(dls::Controller *p) \
{ \
	delete p; \
}

#endif /* end of include guard: CONTROLLER_HPP_RSFU8GQS */
