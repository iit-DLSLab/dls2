Estimator::Estimator(const ID_t &ID_) 
	: PeriodicApp(ID_)
	, signalLink(std::make_shared<dls::DDSParticipant>(
		"Estimator::" + ID_,
		dls::domains::signals))
{ }

std::shared_ptr<dls::DDSParticipant> Estimator::getParticipant()
{
	return this->signalLink;
}
